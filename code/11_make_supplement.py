OUT = ROOT / "manuscript"; OUT.mkdir(exist_ok=True)


def md(df, floatfmt="{:.3g}"):
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    df = df.fillna("").astype(str)
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    return head + "\n".join("| " + " | ".join(r) + " |" for r in df.values) + "\n"


def tab(name, **kw):
    return pd.read_csv(TAB / f"{name}.csv", **kw)


